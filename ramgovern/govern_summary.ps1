# govern_summary.ps1  ramgovern daily summary.
# Reads govern.log (path from govern.json) and writes summary-YYYYMMDD.md beside govern.json for one local date (default:
# today): runs by mode, MB released at 2 s, how far the trimmed processes regrew by the next task run, page-in evidence,
# storms, failures, post-turn spawns, and a VS Code renderer watch. Read-only on everything except the summary file.
# The engine calls it from the scheduled task (summary_hour_interval); it can also be run by hand.
param(
    [string]$Date = '',
    [string]$Config = '',
    [string]$OutDir = ''
)
if (-not $Config) { $Config = Join-Path $PSScriptRoot 'govern.json' }
if (-not $Date) { $Date = ('{0:yyyy-MM-dd}' -f (Get-Date)) }
$dir = Split-Path -Parent $Config
if (-not $OutDir) { $OutDir = $dir }
$logPath = Join-Path $dir 'govern.log'
try { $c = Get-Content -Raw $Config | ConvertFrom-Json; if ($c.log_path) { $logPath = [string]$c.log_path } } catch { }
if (-not (Test-Path $logPath)) { Write-Output "no log at $logPath"; exit 1 }

$lines = @(Get-Content $logPath | Where-Object { $_.StartsWith($Date) })
$rx = '^(?<d>\d{4}-\d\d-\d\d) (?<t>\d\d:\d\d:\d\d) (?<z>[+-]\d\d:\d\d) stage\d (?<mode>task|self|seat) (?<kind>APPLY|DRY|SKIPPED|REFUSED|ERROR)'
$rows = @()
foreach ($ln in $lines) {
    $m = [regex]::Match($ln, $rx)
    if (-not $m.Success) { continue }
    $o = [ordered]@{ t = $m.Groups['t'].Value; mode = $m.Groups['mode'].Value; kind = $m.Groups['kind'].Value; raw = $ln
        idle = 0; all = 0; r0 = 0; r2 = 0; r30 = 0; f0 = 0; f2 = 0; f30 = 0; cpu = 0; trimmed = 0; storm = 'none'; failed = 0
        rgNow = $null; rg30 = $null; rgN = 0; pagesin = $null }
    $x = [regex]::Match($ln, '(\d+) idle of (\d+)'); if ($x.Success) { $o.idle = [int]$x.Groups[1].Value; $o.all = [int]$x.Groups[2].Value }
    $x = [regex]::Match($ln, 'resident (\d+) -> (\d+) \(2s\) -> (\d+) \(30s\) MB')
    if ($x.Success) { $o.r0 = [int]$x.Groups[1].Value; $o.r2 = [int]$x.Groups[2].Value; $o.r30 = [int]$x.Groups[3].Value }
    else { $x = [regex]::Match($ln, 'resident (\d+) MB'); if ($x.Success) { $o.r0 = [int]$x.Groups[1].Value } }
    $x = [regex]::Match($ln, 'free (\d+) -> (\d+) -> (\d+) MB'); if ($x.Success) { $o.f0 = [int]$x.Groups[1].Value; $o.f2 = [int]$x.Groups[2].Value; $o.f30 = [int]$x.Groups[3].Value }
    $x = [regex]::Match($ln, 'cpu-within-30s (\d+) of (\d+)'); if ($x.Success) { $o.cpu = [int]$x.Groups[1].Value; $o.trimmed = [int]$x.Groups[2].Value }
    $x = [regex]::Match($ln, 'storm (.*?); failed (\d+)'); if ($x.Success) { $o.storm = $x.Groups[1].Value; $o.failed = [int]$x.Groups[2].Value }
    $x = [regex]::Match($ln, 'regrow-since-last (\d+) MB vs (\d+) MB at 30 s for (\d+) pids'); if ($x.Success) { $o.rgNow = [int]$x.Groups[1].Value; $o.rg30 = [int]$x.Groups[2].Value; $o.rgN = [int]$x.Groups[3].Value }
    $x = [regex]::Match($ln, 'pagesin-max (\d+)/s'); if ($x.Success) { $o.pagesin = [int]$x.Groups[1].Value }
    $rows += New-Object psobject -Property $o
}
$apply = @($rows | Where-Object { $_.kind -eq 'APPLY' })
$taskApply = @($apply | Where-Object { $_.mode -eq 'task' })
$dry = @($rows | Where-Object { $_.kind -eq 'DRY' })
$bad = @($rows | Where-Object { $_.kind -in 'ERROR', 'REFUSED' -or $_.failed -gt 0 })
$storms = @($apply | Where-Object { $_.storm -ne 'none' })
# test-harness lines (session testcase-*) from govern_posttick_test.py are not production activity
$post = @($lines | Where-Object { $_ -match ' posttick RUN .*SPAWNED' -and $_ -notmatch 'session testcase-' })
$postNoop = @($lines | Where-Object { $_ -match ' posttick .*NOOP' -and $_ -notmatch 'session testcase-' })
$stopHit = @($lines | Where-Object { $_ -match 'HALTED' })

function Sum($set, $prop) { $s = 0; foreach ($e in $set) { $s += [int]$e.$prop }; return $s }
$released2 = (Sum $apply 'r0') - (Sum $apply 'r2')
$held30 = (Sum $apply 'r0') - (Sum $apply 'r30')
$freeGain = 0; foreach ($e in $apply) { $freeGain += ($e.f2 - $e.f0) }
$regrowRows = @($taskApply | Where-Object { $null -ne $_.rgNow })

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# ramgovern daily summary $Date (local time)")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("Generated by govern_summary.ps1 from govern.log; $($lines.Count) log lines for the date.")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("| Measure | Value |")
[void]$sb.AppendLine("|---|---|")
[void]$sb.AppendLine("| Runs with a trim (task / self / seat) | $($apply.Count) ($($taskApply.Count) / $(@($apply | Where-Object {$_.mode -eq 'self'}).Count) / $(@($apply | Where-Object {$_.mode -eq 'seat'}).Count)) |")
[void]$sb.AppendLine("| Dry runs | $($dry.Count) |")
[void]$sb.AppendLine("| Processes trimmed, all runs | $(Sum $apply 'trimmed') |")
[void]$sb.AppendLine("| Resident released at 2 s, summed over runs | $released2 MB |")
[void]$sb.AppendLine("| Resident still released at 30 s, summed | $held30 MB |")
[void]$sb.AppendLine("| Free RAM gained at 2 s, summed over runs | $freeGain MB |")
[void]$sb.AppendLine("| Trimmed processes that used CPU inside 30 s | $(Sum $apply 'cpu') of $(Sum $apply 'trimmed') |")
[void]$sb.AppendLine("| Storms | $($storms.Count) |")
[void]$sb.AppendLine("| Failures (failed trims, errors, refusals) | $($bad.Count) |")
[void]$sb.AppendLine("| Post-turn hook: trims spawned / no-ops logged | $($post.Count) / $($postNoop.Count) |")
[void]$sb.AppendLine("| Halted by govern.stop | $($stopHit.Count) |")
[void]$sb.AppendLine("")
[void]$sb.AppendLine("## Regrow between task runs")
[void]$sb.AppendLine("")
if ($regrowRows.Count -eq 0) { [void]$sb.AppendLine("No task run had a previous run to compare with.") }
else {
    [void]$sb.AppendLine("Each row: the pids the previous task run trimmed, their resident MB at the next run against their 30 s figure. A small gap means the memory stayed released between runs.")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("| Run | Pids | At 30 s after the trim | At this run | Regrown |")
    [void]$sb.AppendLine("|---|---|---|---|---|")
    foreach ($e in $regrowRows) { [void]$sb.AppendLine("| $($e.t) | $($e.rgN) | $($e.rg30) MB | $($e.rgNow) MB | $($e.rgNow - $e.rg30) MB |") }
}
[void]$sb.AppendLine("")
[void]$sb.AppendLine("## Task runs")
[void]$sb.AppendLine("")
if ($taskApply.Count -eq 0) { [void]$sb.AppendLine("None.") }
else {
    [void]$sb.AppendLine("| Time | Idle of all | Resident MB before, 2 s, 30 s | Free MB before, 2 s, 30 s | CPU in 30 s | Storm | Page-ins/s max |")
    [void]$sb.AppendLine("|---|---|---|---|---|---|---|")
    foreach ($e in $taskApply) { [void]$sb.AppendLine("| $($e.t) | $($e.idle) of $($e.all) | $($e.r0), $($e.r2), $($e.r30) | $($e.f0), $($e.f2), $($e.f30) | $($e.cpu) of $($e.trimmed) | $($e.storm) | $($e.pagesin) |") }
}
if ($bad.Count -gt 0 -or $storms.Count -gt 0) {
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("## Failures and storms")
    [void]$sb.AppendLine("")
    foreach ($e in @($bad) + @($storms)) { [void]$sb.AppendLine("- " + $e.raw) }
}
# ---- VS Code renderer watch: renderers are never trimmed, but their size is worth a daily number ----
[void]$sb.AppendLine("")
[void]$sb.AppendLine("## VS Code renderer watch")
[void]$sb.AppendLine("")
try {
    $rp = @{}
    Get-CimInstance Win32_Process -Filter "Name='Code.exe'" -ErrorAction Stop | Where-Object { [string]$_.CommandLine -match '--type=renderer' } | ForEach-Object { $rp[[int]$_.ProcessId] = $true }
    $rl = @(); if ($rp.Count -gt 0) { $rl = @(Get-Process -Id @($rp.Keys) -ErrorAction SilentlyContinue) }
    $totPriv = 0.0; $totWs = 0.0
    foreach ($p in $rl) { $totPriv += $p.PrivateMemorySize64; $totWs += $p.WorkingSet64 }
    [void]$sb.AppendLine("Read at generation time ($((Get-Date).ToString('yyyy-MM-dd HH:mm'))), not at the end of $Date. Renderers are never trimmed; this tracks how much they hold.")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("| Measure | Value |")
    [void]$sb.AppendLine("|---|---|")
    [void]$sb.AppendLine("| Renderer processes | $($rl.Count) |")
    [void]$sb.AppendLine("| Total private bytes | $([math]::Round($totPriv / 1MB)) MB |")
    [void]$sb.AppendLine("| Total resident | $([math]::Round($totWs / 1MB)) MB |")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("Top 5 by private bytes:")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("| pid | Private MB | Resident MB | Age |")
    [void]$sb.AppendLine("|---|---|---|---|")
    foreach ($p in ($rl | Sort-Object PrivateMemorySize64 -Descending | Select-Object -First 5)) {
        $age = 'n/a'; try { $ts = (Get-Date) - $p.StartTime; $age = ('{0} d {1} h' -f [int][math]::Floor($ts.TotalDays), $ts.Hours) } catch { }
        [void]$sb.AppendLine("| $($p.Id) | $([math]::Round($p.PrivateMemorySize64 / 1MB)) | $([math]::Round($p.WorkingSet64 / 1MB)) | $age |")
    }
} catch { [void]$sb.AppendLine("Renderer watch unavailable: $($_.Exception.Message)") }
$out = Join-Path $OutDir ('summary-{0}.md' -f $Date.Replace('-', ''))
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Output "wrote $out ($($apply.Count) trim runs, $($dry.Count) dry runs, $($storms.Count) storms, $($bad.Count) failures)"
